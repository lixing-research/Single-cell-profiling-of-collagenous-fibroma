#!/usr/bin/env python3
"""
Resource Monitor for RNA Velocity Analysis
===========================================

Purpose: Monitor CPU and RAM usage during analysis
- Real-time memory monitoring
- Automatic task termination if RAM exceeds threshold
- Performance metrics logging

Author: Generated by Claude Code
Date: 2025-10-03
"""

import os
import sys
import logging
import psutil
import threading
import time
from datetime import datetime

logger = logging.getLogger(__name__)

class ResourceMonitor:
    """Monitor system resources and enforce limits"""

    def __init__(self, max_ram_gb=450, check_interval=5):
        """
        Initialize resource monitor

        Parameters:
        -----------
        max_ram_gb : int
            Maximum RAM usage in GB (default: 450GB)
        check_interval : int
            How often to check resources in seconds (default: 5s)
        """
        self.max_ram_gb = max_ram_gb
        self.max_ram_bytes = max_ram_gb * 1024 * 1024 * 1024
        self.check_interval = check_interval
        self.monitoring = False
        self.monitor_thread = None
        self.process = psutil.Process(os.getpid())
        self.peak_ram_gb = 0
        self.start_time = None

    def get_current_ram_usage(self):
        """Get current RAM usage in GB"""
        mem_info = self.process.memory_info()
        ram_bytes = mem_info.rss
        ram_gb = ram_bytes / (1024 ** 3)
        return ram_gb

    def get_system_info(self):
        """Get system resource information"""
        cpu_count = psutil.cpu_count(logical=True)
        total_ram = psutil.virtual_memory().total / (1024 ** 3)
        available_ram = psutil.virtual_memory().available / (1024 ** 3)
        cpu_percent = psutil.cpu_percent(interval=1)

        return {
            'cpu_count': cpu_count,
            'total_ram_gb': total_ram,
            'available_ram_gb': available_ram,
            'cpu_percent': cpu_percent
        }

    def print_system_info(self):
        """Print system configuration"""
        info = self.get_system_info()
        logger.info("=" * 80)
        logger.info("System Configuration")
        logger.info("=" * 80)
        logger.info(f"  CPU cores (logical): {info['cpu_count']}")
        logger.info(f"  Total RAM: {info['total_ram_gb']:.1f} GB")
        logger.info(f"  Available RAM: {info['available_ram_gb']:.1f} GB")
        logger.info(f"  CPU usage: {info['cpu_percent']:.1f}%")
        logger.info(f"  RAM limit for this task: {self.max_ram_gb} GB")
        logger.info("")

    def _monitor_loop(self):
        """Background monitoring loop"""
        while self.monitoring:
            current_ram = self.get_current_ram_usage()

            if current_ram > self.peak_ram_gb:
                self.peak_ram_gb = current_ram

            if current_ram > self.max_ram_gb:
                elapsed = time.time() - self.start_time
                logger.error("\n" + "=" * 80)
                logger.error("WARNING  MEMORY LIMIT EXCEEDED!")
                logger.error("=" * 80)
                logger.error(f"  Current RAM usage: {current_ram:.1f} GB")
                logger.error(f"  Maximum allowed: {self.max_ram_gb} GB")
                logger.error(f"  Peak RAM usage: {self.peak_ram_gb:.1f} GB")
                logger.error(f"  Elapsed time: {elapsed/60:.1f} minutes")
                logger.error("")
                logger.error("ACTION REQUIRED:")
                logger.error("  1. Reduce n_jobs parameter (e.g., use 50 instead of 100)")
                logger.error("  2. Process fewer cells (subset your data)")
                logger.error("  3. Increase RAM limit if more RAM is available")
                logger.error("")
                logger.error("Terminating task to protect system stability...")
                logger.error("=" * 80)

                os._exit(1)

            time.sleep(self.check_interval)

    def start(self):
        """Start monitoring"""
        self.monitoring = True
        self.start_time = time.time()
        self.monitor_thread = threading.Thread(target=self._monitor_loop, daemon=True)
        self.monitor_thread.start()
        logger.info(f"OK Resource monitor started (RAM limit: {self.max_ram_gb} GB)")
        logger.info("")

    def stop(self):
        """Stop monitoring and print summary"""
        self.monitoring = False
        if self.monitor_thread:
            self.monitor_thread.join(timeout=1)

        elapsed = time.time() - self.start_time if self.start_time else 0
        current_ram = self.get_current_ram_usage()

        logger.info("")
        logger.info("=" * 80)
        logger.info("Resource Usage Summary")
        logger.info("=" * 80)
        logger.info(f"  Total runtime: {elapsed/60:.1f} minutes")
        logger.info(f"  Peak RAM usage: {self.peak_ram_gb:.1f} GB")
        logger.info(f"  Final RAM usage: {current_ram:.1f} GB")
        logger.info(f"  RAM limit: {self.max_ram_gb} GB")
        logger.info(f"  RAM efficiency: {(self.peak_ram_gb/self.max_ram_gb)*100:.1f}%")
        logger.info("=" * 80)
        logger.info("")

    def get_optimal_n_jobs(self, max_threads=100):
        """
        Calculate optimal number of threads to use

        Parameters:
        -----------
        max_threads : int
            Maximum threads to use (default: 100)

        Returns:
        --------
        int : Recommended number of threads
        """
        cpu_count = psutil.cpu_count(logical=True)

        recommended = min(int(cpu_count * 0.8), max_threads)

        recommended = max(1, recommended)

        return recommended

def estimate_ram_usage(n_cells, n_genes, n_jobs):
    """
    Estimate RAM usage for scVelo analysis

    Parameters:
    -----------
    n_cells : int
        Number of cells
    n_genes : int
        Number of genes
    n_jobs : int
        Number of parallel jobs

    Returns:
    --------
    float : Estimated RAM usage in GB
    """

    base_ram_gb = 5
    data_ram_gb = (n_cells * n_genes * 0.000001) * (1 + n_jobs * 0.1)

    total_ram_gb = base_ram_gb + data_ram_gb
    return total_ram_gb

def check_resource_availability(n_cells, n_genes, n_jobs, max_ram_gb=450):
    """
    Check if resources are sufficient for analysis

    Parameters:
    -----------
    n_cells : int
        Number of cells
    n_genes : int
        Number of genes
    n_jobs : int
        Number of parallel jobs
    max_ram_gb : int
        Maximum RAM allowed

    Returns:
    --------
    tuple : (bool, str) - (is_safe, message)
    """
    estimated_ram = estimate_ram_usage(n_cells, n_genes, n_jobs)
    available_ram = psutil.virtual_memory().available / (1024 ** 3)

    logger.info("Resource Check:")
    logger.info(f"  Dataset: {n_cells:,} cells x {n_genes:,} genes")
    logger.info(f"  Parallel jobs: {n_jobs}")
    logger.info(f"  Estimated RAM needed: {estimated_ram:.1f} GB")
    logger.info(f"  Available system RAM: {available_ram:.1f} GB")
    logger.info(f"  Configured RAM limit: {max_ram_gb} GB")
    logger.info("")

    if estimated_ram > max_ram_gb * 0.9:
        return False, f"WARNING  Estimated RAM usage ({estimated_ram:.1f} GB) may exceed limit ({max_ram_gb} GB). Consider reducing n_jobs."

    if estimated_ram > available_ram:
        return False, f"WARNING  Not enough available RAM. Need {estimated_ram:.1f} GB, have {available_ram:.1f} GB."

    return True, "OK Resources appear sufficient for this analysis"

