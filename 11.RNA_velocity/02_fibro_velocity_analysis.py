#!/usr/bin/env python3
"""
RNA Velocity Analysis for Fibroblast Subtypes (Optimized for High-Performance Server)
======================================================================================

Purpose: Perform RNA velocity analysis on 4 fibroblast subtypes
- Stochastic, Deterministic, and Dynamical models
- Velocity confidence and latent time
- Subtype-specific analyses
- CF vs Normal comparison
- Optimized for AMD EPYC 7502 (128 cores) + 512GB RAM

**Resource Limits:**
- Max threads: 100
- Max RAM: 450GB (auto-kill if exceeded)

Author: Generated by Claude Code
Date: 2025-10-03
Updated: Optimized for HPC
"""

import os
import sys
import time
import logging
import numpy as np
import pandas as pd
import scanpy as sc
import scvelo as scv
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings('ignore')

from resource_monitor import ResourceMonitor, check_resource_availability
from config import LOGGING, OUTPUT_DIRS

os.makedirs(OUTPUT_DIRS['logs'], exist_ok=True)
logging.basicConfig(
    level=getattr(logging, LOGGING['level']),
    format=LOGGING['format'],
    handlers=[
        logging.FileHandler(LOGGING['log_file']),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

scv.settings.verbosity = 3
scv.settings.presenter_view = True
scv.settings.set_figure_params('scvelo', dpi_save=300, dpi=100,
                                transparent=True, fontsize=12, figsize=(8,6))

logger.info("=" * 80)
logger.info("RNA Velocity Analysis - Fibroblast Subtypes (HPC Optimized)")
logger.info("=" * 80)
logger.info("")

DATA_PATH = "./data/fibro_velocity_raw.h5ad"
OUTPUT_DIR = "./results"
os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(f"{OUTPUT_DIR}/figures", exist_ok=True)

MAX_RAM_GB = 450
MAX_THREADS = 100
CHECK_INTERVAL = 10

logger.info(f"scVelo version: {scv.__version__}")
logger.info(f"Scanpy version: {sc.__version__}")
logger.info(f"Input data: {DATA_PATH}")
logger.info(f"Output directory: {OUTPUT_DIR}")
logger.info("")

logger.info("Initializing resource monitor...")
logger.info("-" * 80)

monitor = ResourceMonitor(max_ram_gb=MAX_RAM_GB, check_interval=CHECK_INTERVAL)
monitor.print_system_info()

optimal_n_jobs = monitor.get_optimal_n_jobs(max_threads=MAX_THREADS)
logger.info(f"OK Recommended n_jobs: {optimal_n_jobs}")
logger.info(f"  (Using up to 80% of {monitor.get_system_info()['cpu_count']} cores, max {MAX_THREADS})")
logger.info("")

monitor.start()

step_start = time.time()
logger.info("Step 1: Loading prepared data...")
logger.info("-" * 80)

try:
    adata = sc.read_h5ad(DATA_PATH)

    logger.info(f"Loaded AnnData object:")
    logger.info(f"  - Shape: {adata.shape}")
    logger.info(f"  - Layers: {list(adata.layers.keys())}")
    logger.info(f"  - Cell types: {adata.obs['celltype'].value_counts().to_dict()}")
    logger.info(f"OK Step 1 complete ({time.time()-step_start:.1f}s)")
    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error loading data: {e}")
    monitor.stop()
    sys.exit(1)

logger.info("Checking resource requirements...")
logger.info("-" * 80)

n_cells = adata.n_obs
n_genes = adata.n_vars

is_safe, message = check_resource_availability(
    n_cells=n_cells,
    n_genes=n_genes,
    n_jobs=optimal_n_jobs,
    max_ram_gb=MAX_RAM_GB
)

logger.info(message)

if not is_safe:
    logger.info("")
    logger.info("WARNING  RECOMMENDATION: Reduce n_jobs or subset your data")
    logger.info("WARNING  NOTE: RAM estimation is conservative and may be overestimated")
    logger.info("         Auto-continuing with resource monitoring (will auto-kill if RAM > 450GB)")
    logger.info("")

logger.info("")

step_start = time.time()
logger.info("Step 2: Preprocessing...")
logger.info("-" * 80)

try:

    logger.info("  - Filtering and normalizing...")
    scv.pp.filter_and_normalize(adata, min_shared_counts=20, n_top_genes=2000)

    logger.info("  - Computing neighbors and PCA...")
    sc.pp.neighbors(adata, n_pcs=30, n_neighbors=30)

    logger.info("  - Computing moments...")
    scv.pp.moments(adata, n_pcs=30, n_neighbors=30)

    logger.info(f"OK Preprocessing complete")
    logger.info(f"  - Highly variable genes: {adata.n_vars}")
    logger.info(f"  - Time elapsed: {time.time()-step_start:.1f}s")
    logger.info(f"  - Current RAM: {monitor.get_current_ram_usage():.1f} GB")
    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error in preprocessing: {e}")
    monitor.stop()
    sys.exit(1)

logger.info("Step 3: Velocity estimation...")
logger.info("-" * 80)

adata_preprocessed = adata.copy()

step_start = time.time()
logger.info("  3.1 Stochastic model...")

try:
    adata_stochastic = adata_preprocessed.copy()
    scv.tl.velocity(adata_stochastic, mode='stochastic')
    scv.tl.velocity_graph(adata_stochastic)
    scv.tl.velocity_confidence(adata_stochastic)

    logger.info(f"    OK Stochastic velocity complete ({time.time()-step_start:.1f}s)")
    logger.info(f"    - RAM: {monitor.get_current_ram_usage():.1f} GB")

except Exception as e:
    logger.info(f"    ERROR Error in stochastic model: {e}")

step_start = time.time()
logger.info("  3.2 Deterministic model...")

try:
    adata_deterministic = adata_preprocessed.copy()
    scv.tl.velocity(adata_deterministic, mode='deterministic')
    scv.tl.velocity_graph(adata_deterministic)

    logger.info(f"    OK Deterministic velocity complete ({time.time()-step_start:.1f}s)")
    logger.info(f"    - RAM: {monitor.get_current_ram_usage():.1f} GB")

except Exception as e:
    logger.info(f"    ERROR Error in deterministic model: {e}")

step_start = time.time()
logger.info("  3.3 Dynamical model (this may take 10-30 minutes)...")
adata_dynamical = adata_preprocessed.copy()

logger.info(f"    - Recovering transcriptional dynamics...")
logger.info(f"    - Using {optimal_n_jobs} parallel jobs")
logger.info(f"    - Estimated time: {int(n_cells * 0.5 / optimal_n_jobs)} seconds")

try:
    dynamics_start = time.time()
    scv.tl.recover_dynamics(adata_dynamical, n_jobs=optimal_n_jobs)
    dynamics_time = time.time() - dynamics_start

    logger.info(f"    - Dynamics recovery complete ({dynamics_time:.1f}s = {dynamics_time/60:.1f} min)")
    logger.info(f"    - RAM: {monitor.get_current_ram_usage():.1f} GB")

    logger.info("    - Computing dynamical velocity...")
    scv.tl.velocity(adata_dynamical, mode='dynamical')
    scv.tl.velocity_graph(adata_dynamical)
    scv.tl.velocity_confidence(adata_dynamical)

    logger.info("    - Computing latent time...")
    scv.tl.latent_time(adata_dynamical)

    logger.info("    - Computing velocity pseudotime...")
    scv.tl.velocity_pseudotime(adata_dynamical)

    logger.info(f"    OK Dynamical velocity complete ({time.time()-step_start:.1f}s total)")
    logger.info(f"    - Final RAM: {monitor.get_current_ram_usage():.1f} GB")

except Exception as e:
    logger.info(f"    ERROR Error in dynamical model: {e}")
    logger.info(f"    This might be due to memory constraints. Try reducing n_jobs.")

    if optimal_n_jobs > 20:
        logger.info(f"    Retrying with n_jobs={optimal_n_jobs//2}...")
        try:
            scv.tl.recover_dynamics(adata_dynamical, n_jobs=optimal_n_jobs//2)
            scv.tl.velocity(adata_dynamical, mode='dynamical')
            scv.tl.velocity_graph(adata_dynamical)
            scv.tl.velocity_confidence(adata_dynamical)
            scv.tl.latent_time(adata_dynamical)
            scv.tl.velocity_pseudotime(adata_dynamical)
            logger.info(f"    OK Succeeded with reduced n_jobs")
        except Exception as e2:
            logger.info(f"    ERROR Failed again: {e2}")
            logger.info(f"    Continuing with other models...")

logger.info("")

step_start = time.time()
logger.info("Step 4: Computing additional metrics...")
logger.info("-" * 80)

try:

    adata = adata_dynamical

    logger.info("  - Computing PAGA...")
    scv.tl.paga(adata, groups='celltype')

    if 'celltype' in adata.obs.columns:
        logger.info("  - Ranking cluster-specific dynamical genes...")
        scv.tl.rank_dynamical_genes(adata, groupby='celltype')

        df_rank = scv.get_df(adata, 'rank_dynamical_genes/names')
        df_rank.to_csv(f"{OUTPUT_DIR}/cluster_specific_driver_genes.csv")
        logger.info(f"  OK Saved cluster-specific driver genes")

    logger.info(f"OK All analyses complete ({time.time()-step_start:.1f}s)")
    logger.info(f"  - RAM: {monitor.get_current_ram_usage():.1f} GB")
    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error computing metrics: {e}")

step_start = time.time()
logger.info("Step 5: Saving results...")
logger.info("-" * 80)

try:

    adata_stochastic.write(f"{OUTPUT_DIR}/fibro_velocity_stochastic.h5ad", compression='gzip')
    logger.info(f"  OK Saved stochastic model")

    adata_deterministic.write(f"{OUTPUT_DIR}/fibro_velocity_deterministic.h5ad", compression='gzip')
    logger.info(f"  OK Saved deterministic model")

    adata_dynamical.write(f"{OUTPUT_DIR}/fibro_velocity_dynamical.h5ad", compression='gzip')
    logger.info(f"  OK Saved dynamical model")

    adata.write(f"{OUTPUT_DIR}/fibro_velocity_final.h5ad", compression='gzip')
    logger.info(f"  OK Saved final result")

    logger.info(f"  - Save time: {time.time()-step_start:.1f}s")
    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error saving results: {e}")

step_start = time.time()
logger.info("Step 6: Extracting key metrics...")
logger.info("-" * 80)

try:

    if 'velocity_confidence' in adata.obs.columns:
        confidence_by_celltype = adata.obs.groupby('celltype')['velocity_confidence'].agg(['mean', 'std', 'median'])
        confidence_by_celltype.to_csv(f"{OUTPUT_DIR}/velocity_confidence_by_celltype.csv")
        logger.info("  OK Saved: velocity_confidence_by_celltype.csv")

    if 'latent_time' in adata.obs.columns:
        latent_time_by_celltype = adata.obs.groupby('celltype')['latent_time'].agg(['mean', 'std', 'median'])
        latent_time_by_celltype.to_csv(f"{OUTPUT_DIR}/latent_time_by_celltype.csv")
        logger.info("  OK Saved: latent_time_by_celltype.csv")

    if 'velocity_pseudotime' in adata.obs.columns:
        velo_pseudotime_by_celltype = adata.obs.groupby('celltype')['velocity_pseudotime'].agg(['mean', 'std', 'median'])
        velo_pseudotime_by_celltype.to_csv(f"{OUTPUT_DIR}/velocity_pseudotime_by_celltype.csv")
        logger.info("  OK Saved: velocity_pseudotime_by_celltype.csv")

    if 'fit_likelihood' in adata.var.columns:
        top_driver_genes = adata.var.sort_values('fit_likelihood', ascending=False).head(100)
        top_driver_genes.to_csv(f"{OUTPUT_DIR}/top_driver_genes.csv")
        logger.info("  OK Saved: top_driver_genes.csv")

    if 'fit_alpha' in adata.var.columns:
        kinetic_params = adata.var[['fit_alpha', 'fit_beta', 'fit_gamma',
                                      'fit_likelihood', 'fit_scaling']].dropna()
        kinetic_params.to_csv(f"{OUTPUT_DIR}/kinetic_parameters.csv")
        logger.info("  OK Saved: kinetic_parameters.csv")

    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error extracting metrics: {e}")

step_start = time.time()
logger.info("Step 7: Generating preview plots...")
logger.info("-" * 80)

try:

    plt.rcParams['figure.figsize'] = (8, 6)
    plt.rcParams['savefig.dpi'] = 300

    logger.info("  - Velocity embedding stream...")
    fig, ax = plt.subplots(figsize=(10, 8))
    scv.pl.velocity_embedding_stream(adata, basis='umap', ax=ax, show=False,
                                      title='RNA Velocity - All Fibroblasts')
    plt.savefig(f'{OUTPUT_DIR}/figures/velocity_stream_overall.pdf', bbox_inches='tight')
    plt.close()

    logger.info("  - Velocity colored by cell type...")
    fig, ax = plt.subplots(figsize=(12, 8))
    scv.pl.velocity_embedding_stream(adata, basis='umap', color='celltype',
                                      ax=ax, show=False, legend_loc='right margin',
                                      title='RNA Velocity by Fibroblast Subtype')
    plt.savefig(f'{OUTPUT_DIR}/figures/velocity_stream_by_celltype.pdf', bbox_inches='tight')
    plt.close()

    if 'latent_time' in adata.obs.columns:
        logger.info("  - Latent time...")
        fig, ax = plt.subplots(figsize=(10, 8))
        scv.pl.scatter(adata, color='latent_time', color_map='gnuplot', size=80,
                       ax=ax, show=False, title='Latent Time')
        plt.savefig(f'{OUTPUT_DIR}/figures/latent_time.pdf', bbox_inches='tight')
        plt.close()

    if 'velocity_confidence' in adata.obs.columns:
        logger.info("  - Velocity confidence...")
        fig, ax = plt.subplots(figsize=(10, 8))
        scv.pl.scatter(adata, color='velocity_confidence', perc=[5, 95],
                       ax=ax, show=False, title='Velocity Confidence')
        plt.savefig(f'{OUTPUT_DIR}/figures/velocity_confidence.pdf', bbox_inches='tight')
        plt.close()

    logger.info("  - PAGA trajectory graph...")
    fig, ax = plt.subplots(figsize=(10, 8))
    scv.pl.paga(adata, basis='umap', size=50, alpha=.1, min_edge_width=2,
                node_size_scale=1.5, ax=ax, show=False,
                title='PAGA Trajectory - Fibroblast Subtypes')
    plt.savefig(f'{OUTPUT_DIR}/figures/paga_trajectory.pdf', bbox_inches='tight')
    plt.close()

    logger.info(f"  - Plot generation time: {time.time()-step_start:.1f}s")
    logger.info("")

except Exception as e:
    logger.info(f"ERROR Error generating plots: {e}")

monitor.stop()

logger.info("=" * 80)
logger.info("OK RNA Velocity Analysis Complete!")
logger.info("=" * 80)
logger.info("")
logger.info(f"Results saved in: {OUTPUT_DIR}")
logger.info("")
logger.info("Key outputs:")
logger.info("  1. Final velocity data: fibro_velocity_final.h5ad")
logger.info("  2. Model variants: fibro_velocity_{stochastic,deterministic,dynamical}.h5ad")
logger.info("  3. Metrics CSV files:")
logger.info("     - velocity_confidence_by_celltype.csv")
logger.info("     - latent_time_by_celltype.csv")
logger.info("     - velocity_pseudotime_by_celltype.csv")
logger.info("     - top_driver_genes.csv")
logger.info("     - cluster_specific_driver_genes.csv (NEW)")
logger.info("     - kinetic_parameters.csv (NEW)")
logger.info("  4. Preview figures in: results/figures/")
logger.info("")
logger.info("Performance tips:")
logger.info(f"  - Used {optimal_n_jobs} parallel jobs")
logger.info(f"  - Peak RAM usage: {monitor.peak_ram_gb:.1f} GB / {MAX_RAM_GB} GB")
logger.info("")
logger.info("Next step: Generate detailed visualizations")
logger.info("  python 03_fibro_visualization.py")
logger.info("")
