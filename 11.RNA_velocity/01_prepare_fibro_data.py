#!/usr/bin/env python3
"""
RNA Velocity Data Preparation for Fibroblast Subtypes
======================================================

Purpose: Prepare data for RNA velocity analysis of 4 fibroblast subtypes
- Load fibroblast_annotated.rds data
- Load spliced/unspliced matrices from dnbc4tools output
- Match barcodes and integrate metadata
- Save as h5ad format for velocity analysis

Author: Generated by Claude Code
Date: 2025-10-03
"""

import os
import sys
import numpy as np
import pandas as pd
import scanpy as sc
import anndata
from scipy import io
from scipy.sparse import csr_matrix
import gzip
import warnings
warnings.filterwarnings('ignore')

print("=" * 80)
print("RNA Velocity Data Preparation - Fibroblast Subtypes")
print("=" * 80)
print()

from config import DATA_PATHS

FIBRO_RDS_PATH = DATA_PATHS['fibro_rds']
CF_VELOCITY_DIR = DATA_PATHS['cf_velocity']
NORMAL_VELOCITY_DIR = DATA_PATHS['normal_velocity']

OUTPUT_DIR = "./data"
os.makedirs(OUTPUT_DIR, exist_ok=True)

print(f"Configuration:")
print(f"  - Fibroblast data: {FIBRO_RDS_PATH}")
print(f"  - CF velocity matrices: {CF_VELOCITY_DIR}")
print(f"  - Normal velocity matrices: {NORMAL_VELOCITY_DIR}")
print(f"  - Output directory: {OUTPUT_DIR}")
print()

print("Step 1: Extracting fibroblast metadata from RDS...")
print("-" * 80)

r_script = """
library(Seurat)

fibro <- readRDS("{rds_path}")

meta <- fibro@meta.data

barcodes <- rownames(meta)

if("umap" %in% names(fibro@reductions)) {{
  umap_coords <- fibro@reductions$umap@cell.embeddings
  meta$UMAP_1 <- umap_coords[, 1]
  meta$UMAP_2 <- umap_coords[, 2]
}}

if("pca" %in% names(fibro@reductions)) {{
  pca_coords <- fibro@reductions$pca@cell.embeddings[, 1:50]
  pca_df <- as.data.frame(pca_coords)
  colnames(pca_df) <- paste0("PC_", 1:ncol(pca_df))
  meta <- cbind(meta, pca_df)
}}

write.csv(meta, "{output_dir}/fibro_metadata.csv", row.names = TRUE)

writeLines(barcodes, "{output_dir}/fibro_barcodes.txt")

cat("OK Exported", nrow(meta), "cells\\n")
cat("OK Cell types:", paste(unique(meta$celltype), collapse=", "), "\\n")
""".format(rds_path=FIBRO_RDS_PATH, output_dir=OUTPUT_DIR)

r_script_path = f"{OUTPUT_DIR}/extract_metadata.R"
with open(r_script_path, 'w') as f:
    f.write(r_script)

os.system(f"Rscript {r_script_path}")

meta_df = pd.read_csv(f"{OUTPUT_DIR}/fibro_metadata.csv", index_col=0)
print(f"OK Loaded metadata for {len(meta_df)} fibroblast cells")
print(f"OK Cell types: {meta_df['celltype'].value_counts().to_dict()}")
print()

print("Step 2: Loading spliced/unspliced matrices...")
print("-" * 80)

def load_velocity_matrices(velocity_dir, sample_name):
    """Load spliced/unspliced matrices from velocity directory"""

    print(f"  Loading {sample_name} sample...")

    spliced_path = os.path.join(velocity_dir, "spliced.mtx.gz")
    unspliced_path = os.path.join(velocity_dir, "unspliced.mtx.gz")
    barcodes_path = os.path.join(velocity_dir, "barcodes.tsv.gz")
    features_path = os.path.join(velocity_dir, "features.tsv.gz")

    with gzip.open(spliced_path, 'rb') as f:
        spliced = io.mmread(f).T.tocsr()

    with gzip.open(unspliced_path, 'rb') as f:
        unspliced = io.mmread(f).T.tocsr()

    with gzip.open(barcodes_path, 'rt') as f:
        barcodes = [line.strip() for line in f]

    with gzip.open(features_path, 'rt') as f:
        features = [line.strip().split('\t')[0] for line in f]

    print(f"    - Cells: {len(barcodes)}")
    print(f"    - Genes: {len(features)}")
    print(f"    - Spliced shape: {spliced.shape}")
    print(f"    - Unspliced shape: {unspliced.shape}")

    return spliced, unspliced, barcodes, features, sample_name

cf_spliced, cf_unspliced, cf_barcodes, cf_features, _ = load_velocity_matrices(
    CF_VELOCITY_DIR, "CF"
)

normal_spliced, normal_unspliced, normal_barcodes, normal_features, _ = load_velocity_matrices(
    NORMAL_VELOCITY_DIR, "Normal"
)

print()

print("Step 3: Matching barcodes and filtering fibroblast cells...")
print("-" * 80)

cf_barcodes_prefixed = [f"CF_{bc}" for bc in cf_barcodes]
normal_barcodes_prefixed = [f"Normal_{bc}" for bc in normal_barcodes]

all_velocity_barcodes = cf_barcodes_prefixed + normal_barcodes_prefixed

velocity_barcode_to_idx = {bc: i for i, bc in enumerate(all_velocity_barcodes)}

print("Aligning gene features between CF and Normal samples...")
print(f"  - CF genes: {len(cf_features)}")
print(f"  - Normal genes: {len(normal_features)}")

common_genes = list(set(cf_features) & set(normal_features))
common_genes.sort()
print(f"  - Common genes: {len(common_genes)}")

cf_gene_indices = [cf_features.index(gene) for gene in common_genes]
normal_gene_indices = [normal_features.index(gene) for gene in common_genes]

cf_spliced_subset = cf_spliced[:, cf_gene_indices]
cf_unspliced_subset = cf_unspliced[:, cf_gene_indices]
normal_spliced_subset = normal_spliced[:, normal_gene_indices]
normal_unspliced_subset = normal_unspliced[:, normal_gene_indices]

all_features = common_genes

from scipy.sparse import vstack
spliced_combined = vstack([cf_spliced_subset, normal_spliced_subset])
unspliced_combined = vstack([cf_unspliced_subset, normal_unspliced_subset])

print(f"OK Combined velocity matrices (common genes only):")
print(f"  - Total cells: {len(all_velocity_barcodes)}")
print(f"  - Total genes: {len(all_features)}")
print()

fibro_barcodes = meta_df.index.tolist()

matched_indices = []
matched_fibro_barcodes = []
unmatched_count = 0

for fibro_bc in fibro_barcodes:

    if fibro_bc in velocity_barcode_to_idx:
        matched_indices.append(velocity_barcode_to_idx[fibro_bc])
        matched_fibro_barcodes.append(fibro_bc)
    else:

        parts = fibro_bc.split('_')

        cell_part = None
        for i, part in enumerate(parts):
            if part.startswith('CELL'):

                if i + 1 < len(parts):
                    cell_part = f"{part}_{parts[i+1]}"
                    break

        if cell_part:

            if fibro_bc.startswith('CF'):
                velocity_bc = f"CF_{cell_part}"
            elif fibro_bc.startswith('Normal'):
                velocity_bc = f"Normal_{cell_part}"
            else:

                velocity_bc_cf = f"CF_{cell_part}"
                velocity_bc_normal = f"Normal_{cell_part}"

                if velocity_bc_cf in velocity_barcode_to_idx:
                    matched_indices.append(velocity_barcode_to_idx[velocity_bc_cf])
                    matched_fibro_barcodes.append(fibro_bc)
                    continue
                elif velocity_bc_normal in velocity_barcode_to_idx:
                    matched_indices.append(velocity_barcode_to_idx[velocity_bc_normal])
                    matched_fibro_barcodes.append(fibro_bc)
                    continue
                else:
                    unmatched_count += 1
                    continue

            if velocity_bc in velocity_barcode_to_idx:
                matched_indices.append(velocity_barcode_to_idx[velocity_bc])
                matched_fibro_barcodes.append(fibro_bc)
            else:
                unmatched_count += 1
        else:
            unmatched_count += 1

print(f"OK Barcode matching results:")
print(f"  - Matched: {len(matched_indices)} cells")
print(f"  - Unmatched: {unmatched_count} cells")
print(f"  - Match rate: {len(matched_indices)/len(fibro_barcodes)*100:.1f}%")
print()

if len(matched_indices) == 0:
    print("ERROR ERROR: No barcodes matched!")
    print("  Showing example barcodes for debugging:")
    print(f"  Fibro barcodes: {fibro_barcodes[:5]}")
    print(f"  Velocity barcodes: {all_velocity_barcodes[:5]}")
    sys.exit(1)

fibro_spliced = spliced_combined[matched_indices, :]
fibro_unspliced = unspliced_combined[matched_indices, :]
fibro_meta = meta_df.loc[matched_fibro_barcodes]

print(f"OK Filtered to fibroblast cells:")
print(f"  - Spliced matrix: {fibro_spliced.shape}")
print(f"  - Unspliced matrix: {fibro_unspliced.shape}")
print(f"  - Metadata: {fibro_meta.shape}")
print()

print("Step 4: Creating AnnData object...")
print("-" * 80)

adata = anndata.AnnData(
    X=fibro_spliced,
    obs=fibro_meta,
    var=pd.DataFrame(index=all_features)
)

adata.layers['spliced'] = fibro_spliced
adata.layers['unspliced'] = fibro_unspliced

if 'UMAP_1' in adata.obs.columns and 'UMAP_2' in adata.obs.columns:
    adata.obsm['X_umap'] = adata.obs[['UMAP_1', 'UMAP_2']].values
    print("OK Added UMAP coordinates")

pca_cols = [col for col in adata.obs.columns if col.startswith('PC_')]
if len(pca_cols) > 0:
    adata.obsm['X_pca'] = adata.obs[pca_cols].values
    print(f"OK Added PCA coordinates ({len(pca_cols)} PCs)")

print()
print("AnnData object summary:")
print(f"  - Shape: {adata.shape}")
print(f"  - Layers: {list(adata.layers.keys())}")
print(f"  - obsm: {list(adata.obsm.keys())}")
print(f"  - Cell types: {adata.obs['celltype'].value_counts().to_dict()}")
print()

print("Step 5: Saving prepared data...")
print("-" * 80)

output_h5ad = f"{OUTPUT_DIR}/fibro_velocity_raw.h5ad"
adata.write_h5ad(output_h5ad)

print(f"OK Saved: {output_h5ad}")
print()

summary = {
    'total_cells': adata.n_obs,
    'total_genes': adata.n_vars,
    'celltype_counts': adata.obs['celltype'].value_counts().to_dict(),
    'sample_counts': adata.obs['orig.ident'].value_counts().to_dict() if 'orig.ident' in adata.obs.columns else {},
}

import json
with open(f"{OUTPUT_DIR}/data_summary.json", 'w') as f:
    json.dump(summary, f, indent=2)

print("=" * 80)
print("OK Data preparation complete!")
print("=" * 80)
print()
print("Next step: Run velocity analysis")
print("  python 02_fibro_velocity_analysis.py")
print()
